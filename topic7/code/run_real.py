def benchmark(Dp, Df, SH, c):
    """common.standard_benchmark with the logs drawn from the learning sessions and every policy scored on the scoring
    sessions; adds our structured model (DP, MC, Q-learning), the baselines from published work and the shift scores"""
    n, S = CFG["n_eval"], CFG["seeds"]
    q_extra = c["q_extra"]
    d_or = rollout(Dp, Dp.behavior, np.random.default_rng(9999), CFG["n_oracle"])
    m_or = build_mdp(d_or, Dp)
    pi_or = fill_policy(value_iteration(m_or)[0], m_or, behavior_mode(d_or, Dp))
    rule = np.array([Dp.rule(s) for s in range(Dp.nS)])
    res = {"methods": {}, "curves": {"Monte Carlo": [], "Q-learning": []}, "policies": {},
           "agree": {"Monte Carlo": [], "Q-learning": []}, "optimism_gap": [], "pi_equals_vi": [],
           "true_curves": {k: [] for k in ("Monte Carlo|sir", "Q-learning|sir", "Monte Carlo|ours", "Q-learning|ours")},
           "shift": {"nominal": {}, **{k: {} for k in SH}}, "ep_mean": {}}
    eps = {}

    def record(name, pol, seed_idx):
        r, inf = score(Df, pol, n)
        e = res["methods"].setdefault(name, {"J": [], "Jor": [], "info": {}})
        e["J"].append(float(r.mean()))
        e["Jor"].append(J(m_or, pol) if isinstance(pol, np.ndarray) else float("nan"))
        for k, v in inf.items():
            e["info"].setdefault(k, []).append(float(v.mean()))
        eps.setdefault(name, []).append(r)
        res["shift"]["nominal"].setdefault(name, []).append(float(r.mean()))
        for k, sim in SH.items():
            res["shift"][k].setdefault(name, []).append(float(score(sim, pol, n)[0].mean()))
        if seed_idx == 0 and isinstance(pol, np.ndarray):
            res["policies"][name] = np.asarray(pol).tolist()

    record("Rule", rule, 0)
    record("Oracle DP", pi_or, 0)
    # baselines from published work (single policies; threshold and k chosen on the scoring sessions)
    thr = {th: float(score(Df, pl.threshold_policy(th), n)[0].mean()) for th in (0.2, 0.25, 0.3, 0.35)}
    fixed = {k: float(score(Df, np.full(Df.nS, k), n)[0].mean()) for k in range(Df.nA)}
    best_th, best_k = max(thr, key=thr.get), max(fixed, key=fixed.get)
    record("Single session optimiser", pl.one_session_optimiser(q_extra), 0)
    record("Threshold double booking", pl.threshold_policy(best_th), 0)
    record("Fixed booking", np.full(Df.nS, best_k), 0)
    res["baselines"] = dict(threshold={str(k): v for k, v in thr.items()}, fixed={str(k): v for k, v in fixed.items()},
                            best_threshold=best_th, best_k=best_k)
    log("benchmark: single policies scored")

    true_J = lambda pi: float(eval_policy(Df, pi, seed=777, n_eps=CFG["ckpt_eps"])[0].mean())
    for sd in range(S):
        d = rollout(Dp, Dp.behavior, np.random.default_rng(1000 + sd), CFG["n_logged"])
        m = build_mdp(d, Dp)
        bm = behavior_mode(d, Dp)
        pi_dp, V, Q = value_iteration(m)
        pi_pi, _ = policy_iteration(m)
        res["pi_equals_vi"].append(bool(abs(J(m, pi_dp) - J(m, pi_pi)) < 1e-6))
        pi_dp = fill_policy(pi_dp, m, bm)
        side = {"Monte Carlo": [], "Q-learning": []}

        def cf(p, key, m=m, bm=bm):
            fp = fill_policy(p, m, bm)
            side[key].append(true_J(fp))
            return J(m_or, fp)
        pi_mc, _, c_mc = mc_control(m, np.random.default_rng(2000 + sd), CFG["steps"], ckpt_fn=lambda p: cf(p, "Monte Carlo"))
        pi_q, _, c_q = q_learning(m, np.random.default_rng(3000 + sd), CFG["steps"], ckpt_fn=lambda p: cf(p, "Q-learning"))
        res["optimism_gap"].append(float(J(m, pi_dp) - J(m_or, pi_dp)))
        res["curves"]["Monte Carlo"].append(c_mc.tolist()); res["curves"]["Q-learning"].append(c_q.tolist())
        res["true_curves"]["Monte Carlo|sir"].append([[float(x), v] for x, v in zip(c_mc[:, 0], side["Monte Carlo"])])
        res["true_curves"]["Q-learning|sir"].append([[float(x), v] for x, v in zip(c_q[:, 0], side["Q-learning"])])
        pi_mc, pi_q = fill_policy(pi_mc, m, bm), fill_policy(pi_q, m, bm)
        vis = m.visits >= 5
        for nm, p in (("Monte Carlo", pi_mc), ("Q-learning", pi_q)):
            res["agree"][nm].append(float((p[vis] == pi_dp[vis]).mean()) if vis.any() else 1.0)
        record("Behavior", bm, sd); record("DP", pi_dp, sd)
        record("Monte Carlo", pi_mc, sd); record("Q-learning", pi_q, sd)
        # our structured model, from the same logs
        ms = pl.real_model(d, Dp, q_extra)
        record("Ours: DP", value_iteration(ms)[0], sd)
        p, _, cv = mc_control(ms, np.random.default_rng(2000 + sd), CFG["steps"], ckpt_fn=true_J)
        record("Ours: Monte Carlo", p, sd); res["true_curves"]["Monte Carlo|ours"].append(cv.tolist())
        p, _, cv = q_learning(ms, np.random.default_rng(3000 + sd), CFG["steps"], ckpt_fn=true_J)
        record("Ours: Q-learning", p, sd); res["true_curves"]["Q-learning|ours"].append(cv.tolist())
        log(f"benchmark seed {sd}: DP {res['methods']['DP']['J'][-1]:.2f}  ours {res['methods']['Ours: DP']['J'][-1]:.2f}")
    res["ep_mean"] = {k: np.mean(v, 0).tolist() for k, v in eps.items()}
    res["J_oracle_model"] = {"Oracle DP": J(m_or, pi_or), "Rule": J(m_or, rule)}
    res["n_states"], res["n_actions"] = Dp.nS, Dp.nA
    res["config"] = dict(n_eps=CFG["n_logged"], n_oracle=CFG["n_oracle"], steps=CFG["steps"], seeds=S, n_eval=n)
    res["m_or"] = m_or
    return res


# ============================================================================= Paper 7's schedule and shift study (ideas.idea7), on real data
def schedule_study(Dp, Df, SH):
    T = CFG["steps"]
    qopt = 14.0 * (1 - Dp.gamma ** 40) / (1 - Dp.gamma)
    SCH = {"eps=0.1 const": (lambda k, t: 0.1, 0.0), "eps exp. decay": (eps_exp, 0.0),
           "GLIE 1/k": (lambda k, t: max(0.02, (t / 50.0) / (t / 50.0 + k)), 0.0),
           "Optimistic init": (lambda k, t: 0.02, 0.5 * qopt), "Near-greedy (0.02)": (lambda k, t: 0.02, 0.0)}
    d_or = rollout(Dp, Dp.behavior, np.random.default_rng(9999), CFG["n_oracle"]); m_or = build_mdp(d_or, Dp)
    pi_or, _, _ = value_iteration(m_or); J_opt = J(m_or, pi_or)
    J_beh = J(m_or, behavior_mode(d_or, Dp))
    sh = {"nominal": Df, **SH}
    CUR = {a: {s: [] for s in SCH} for a in ("Q-learning", "Monte Carlo")}
    FIN = {a: {s: {k: [] for k in sh} for s in SCH} for a in CUR}
    for sd in range(CFG["sched_seeds"]):
        data = rollout(Dp, Dp.behavior, np.random.default_rng(700 + sd), CFG["n_logged"])
        m = build_mdp(data, Dp); bm = behavior_mode(data, Dp)
        cf = (lambda p, m=m, bm=bm: J(m_or, fill_policy(p, m, bm)))
        for sn, (ef, q0) in SCH.items():
            for an, fn in (("Q-learning", q_learning), ("Monte Carlo", mc_control)):
                p, _, c = fn(m, np.random.default_rng([sd, list(SCH).index(sn), 1]), T, eps_fn=ef, q0=q0, ckpt_fn=cf)
                CUR[an][sn].append(c.tolist())
                p = fill_policy(p, m, bm)
                for k, sim in sh.items():
                    FIN[an][sn][k].append(float(eval_policy(sim, p, n_eps=CFG["sched_eval"])[0].mean()))
        log(f"schedule study seed {sd}")
    t90 = {a: {} for a in CUR}; auc = {a: {} for a in CUR}; fin = {a: {} for a in CUR}
    for a in CUR:
        for sn in SCH:
            cs = CUR[a][sn]
            t90[a][sn] = steps_to_fraction(cs, J_beh + 0.9 * (J_opt - J_beh))
            auc[a][sn] = [float(np.mean([(v[1] - J_beh) / (J_opt - J_beh) for v in c])) for c in cs]
            fin[a][sn] = [float((c[-1][1] - J_beh) / (J_opt - J_beh)) for c in cs]
    rule = np.array([Dp.rule(s) for s in range(Dp.nS)])
    d700 = rollout(Dp, Dp.behavior, np.random.default_rng(700), CFG["n_logged"]); m700 = build_mdp(d700, Dp)
    dp_pol = fill_policy(value_iteration(m700)[0], m700, rule)
    shift_res = {}
    for k, sim in sh.items():
        shift_res[k] = {}
        for nm, p in (("Rule", rule), ("DP", dp_pol)):
            shift_res[k][nm] = float(eval_policy(sim, p, n_eps=CFG["shift_ref_eval"])[0].mean())
        for a in CUR:
            shift_res[k][a + " (eps exp)"] = float(np.mean(FIN[a]["eps exp. decay"][k]))
    return dict(schedules=list(SCH), J_opt=J_opt, J_beh=J_beh, curves=CUR,
                t90={a: {s: [None if np.isnan(x) else float(x) for x in t90[a][s]] for s in SCH} for a in CUR},
                auc={a: {s: dict(mean=float(np.mean(auc[a][s])), ci=ci95(auc[a][s]), per_seed=auc[a][s]) for s in SCH} for a in CUR},
                final={a: {s: dict(mean=float(np.mean(fin[a][s])), ci=ci95(fin[a][s])) for s in SCH} for a in CUR},
                shift={a: {s: {k: float(np.mean(FIN[a][s][k])) for k in sh} for s in SCH} for a in CUR}, shift_ref=shift_res,
                reach_rate={a: {s: float(np.mean(~np.isnan(t90[a][s]))) for s in SCH} for a in CUR})


