"""run_real.py -- version 3: Paper 7's whole experiment run on the real Kaggle data, together with our method and the
baselines from published work. Every method learns from the same logs (drawn from the real sessions of 16 to 25 May
2016) and is scored on the same held-out real sessions (30 May to 8 June 2016).

    python topic7/code/run_real.py             full run (writes topic7/code/out/topic7_real/)
    python topic7/code/run_real.py --quick     smoke test (writes topic7/code/out/topic7_quick/real/, not committed)
    python topic7/code/run_real.py --figures   redraw the figures from the saved results.json

This file only imports the existing code (rl_core, common, ideas, noshow_data, real_clinic, planner) and changes none
of it. Paper 7's experiment (common.standard_benchmark and ideas.idea7) is repeated here step by step with one change:
logs come from the real learning sessions and every policy is scored on the real scoring sessions.

What the real table cannot give, and what is done instead (the paper states the same):
  * no overbooking decisions: the logs are generated by Paper 7's behaviour policy (its rule with 25% random choices)
    on real sessions; who comes and who does not is what the table records
  * no waiting list: Paper 7's waiting list rule is kept (Poisson(1.5) new patients per session), the one simulated part
  * no clinics or slots: a session is one neighbourhood on one day (at least 5 appointments) with 10 regular slots
  * only 26 days: "150 logged days" are 150 runs of 40 sessions drawn from the 506 real learning sessions
  * no hidden true no-show rate: the state uses the classifier's predicted risk band (slots x risk x waiting list)
  * no shift knob: the no-show rate of the scoring sessions is moved by flipping the recorded outcome of randomly chosen
    patients (+0.08 and -0.05); the predicted risks are not changed, and the real drift between the learning and the
    scoring weeks is reported as well
"""
