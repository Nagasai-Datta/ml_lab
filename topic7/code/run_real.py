# ============================================================================= data
def flip_outcomes(sessions, pool, delta, seed):
    """move the no-show rate by delta: a random share of recorded shows become no-shows (delta > 0) or of recorded
    no-shows become shows (delta < 0); predicted risks are left as they are"""
    rng = np.random.default_rng(seed)
    rate = float(np.concatenate([pool[d][1] for d in pool]).mean())
    def flip(y):
        y = y.copy(); u = rng.random(len(y))
        if delta > 0:
            y[(y == 0) & (u < delta / (1 - rate))] = 1
        else:
            y[(y == 1) & (u < -delta / rate)] = 0
        return y
    s2 = {d: [(p, flip(y)) for p, y in sessions[d]] for d in sessions}
    p2 = {d: (pool[d][0], flip(pool[d][1])) for d in pool}
    return s2, p2


_C = {}


def build(lam=1.5, wait_cost=0.4):
    """learning clinic, scoring clinic and the shifted scoring clinics, all from the real table"""
    if not _C:
        df = nd.load()
        test, info = nd.fit_predictor(df)
        past, fut = test[test.AD < CFG["split"]], test[test.AD >= CFG["split"]]
        sp, pp = nd.build_sessions(past); sf, pf = nd.build_sessions(fut)
        shifted = {k: flip_outcomes(sf, pf, dl, seed=500 + i) for i, (k, dl) in enumerate(CFG["shifts"].items())}
        _C.update(df=df, info=info, past=past, fut=fut, sp=sp, pp=pp, sf=sf, pf=pf, RE=risk_edges(sp),
                  q_extra=float(1 - past.p.mean()), shifted=shifted)
    c = _C
    Dp = RealClinic(c["sp"], c["pp"], c["RE"], lam, wait_cost)
    Df = RealClinic(c["sf"], c["pf"], c["RE"], lam, wait_cost)
    SH = {k: RealClinic(s, p, c["RE"], lam, wait_cost) for k, (s, p) in c["shifted"].items()}
    return Dp, Df, SH, c


def session_rate(sessions):
    return float(np.concatenate([y for d in sessions for _, y in sessions[d]]).mean())


# ============================================================================= scoring helpers
def evaluate(dom, act, n, seed=12345):
    """like rl_core.eval_policy, for policies that look at today's patients (act(dom, s) -> k);
    same common random numbers, so a table policy gets exactly the eval_policy result"""
    rets = np.zeros(n); infos = {k: np.zeros(n) for k in dom.info_keys}
    for e in range(n):
        rng = np.random.default_rng([seed, e]); s = dom.reset(rng); disc = 1.0
        for _ in range(dom.max_steps):
            s, r, done, info, dur = dom.step(int(act(dom, s)), rng)
            rets[e] += disc * r; disc *= dom.gamma ** dur
            for k in dom.info_keys:
                infos[k][e] += info.get(k, 0.0)
            if done:
                break
    return rets, infos


def score(dom, pol, n):
    return eval_policy(dom, pol, n_eps=n) if isinstance(pol, np.ndarray) else evaluate(dom, pol, n)


