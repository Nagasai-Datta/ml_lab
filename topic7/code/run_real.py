def data_size(Dp, Df, c):
    out = {}
    for nlog in CFG["sizes"]:
        sj, oj = [], []
        for sd in range(CFG["size_seeds"]):
            d = rollout(Dp, Dp.behavior, np.random.default_rng(1000 + sd), nlog)
            m = build_mdp(d, Dp); bm = behavior_mode(d, Dp)
            sj.append(float(eval_policy(Df, fill_policy(value_iteration(m)[0], m, bm), n_eps=CFG["n_eval"])[0].mean()))
            oj.append(float(eval_policy(Df, value_iteration(pl.real_model(d, Dp, c["q_extra"]))[0], n_eps=CFG["n_eval"])[0].mean()))
        out[str(nlog)] = {"DP": sj, "Ours: DP": oj}
        log(f"data size {nlog}: DP {np.mean(sj):.2f}  ours {np.mean(oj):.2f}")
    return out


def demand(c):
    out = {}
    for wc, lam in CFG["demand"]:
        Dp2, Df2, _, _ = build(lam, wc)
        nn = CFG["n_eval_demand"]
        one = float(evaluate(Df2, pl.one_session_optimiser(c["q_extra"]), nn)[0].mean())
        fx = {k: float(eval_policy(Df2, np.full(Df2.nS, k), n_eps=nn)[0].mean()) for k in range(5)}
        sj, oj = [], []
        for sd in range(CFG["demand_seeds"]):
            d = rollout(Dp2, Dp2.behavior, np.random.default_rng(1000 + sd), CFG["n_logged"])
            m = build_mdp(d, Dp2); bm = behavior_mode(d, Dp2)
            sj.append(float(eval_policy(Df2, fill_policy(value_iteration(m)[0], m, bm), n_eps=nn)[0].mean()))
            oj.append(float(eval_policy(Df2, value_iteration(pl.real_model(d, Dp2, c["q_extra"]))[0], n_eps=nn)[0].mean()))
        out[f"{wc}|{lam}"] = {"wait_cost": wc, "arrivals": lam, "DP": sj, "Ours: DP": oj,
                              "Single session optimiser": one, "Best fixed booking": max(fx.values())}
        log(f"demand {wc}, {lam}: ours {np.mean(oj):.2f}  single session {one:.2f}  DP {np.mean(sj):.2f}")
    return out


